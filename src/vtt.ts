/**
 * WEBVTT INTO WORDS, so a published transcript can be scanned and verified.
 *
 * About six per cent of podcast feeds ship a `<podcast:transcript>`, and when
 * they do it is the best thing Scout can find: a real transcript, published
 * by the people who made the audio, with timings, needing no transcription
 * and no permission. Two of the three feeds tested had one.
 *
 * A CUE IS NOT A WORD TIMING, which is the whole difficulty. A cue is five to
 * seven words over one to two seconds. The boundaries are good — better than
 * a recogniser's, usually, because they came off an alignment — and the
 * position of each word INSIDE the cue is not in the file at all. This
 * interpolates it, and `TimingSource` has a `caption` tier at 400ms saying
 * what that is worth. Nothing frame-accurate may use these, and `align.ts`
 * is where that refusal lives.
 *
 * THREE THINGS IN REAL FILES WOULD OTHERWISE BECOME WORDS:
 *
 *   A SPEAKER LABEL. "JACK: I just came back from DEFCON" — the label is not
 *   spoken. Kept, the verifier tries to match "JACK" as a word, and a quote
 *   spanning a speaker change mismatches on a word nobody said.
 *
 *   NOTE blocks. Descript writes "NOTE This file was generated by Descript"
 *   at the top of every file it makes. Kept, the transcript opens with an
 *   advertisement.
 *
 *   Markup. Voice tags (`<v Jack>`), class tags (`<c.loud>`) and inline
 *   timestamps (`<00:00:01.000>`) are all legal inside cue text.
 */

import type { IndexedWord } from "./align.ts";
import { decodeEntities } from "./xml.ts";

/** `HH:MM:SS.mmm` or `MM:SS.mmm`, which the spec allows. */
function stampMs(s: string): number | null {
  const m = s.trim().match(/^(?:(\d{1,3}):)?(\d{1,2}):(\d{2})[.,](\d{1,3})$/);
  if (!m) return null;
  const h = m[1] ? Number(m[1]) : 0;
  const min = Number(m[2]);
  const sec = Number(m[3]);
  if (min > 59 || sec > 59) return null;
  return ((h * 60 + min) * 60 + sec) * 1000 + Number(m[4].padEnd(3, "0"));
}

export interface Cue {
  startMs: number;
  endMs: number;
  text: string;
  /** The speaker, where the file names one. Not a word. */
  speaker?: string;
}

/**
 * A speaker label at the start of a cue: "JACK:" or "Jack Rhysider:".
 *
 * The label must be CAPITALISED and the colon followed by whitespace or the
 * end of the cue. Both halves matter. Without the capitals, "note: this is
 * said aloud" loses its first word. Without allowing the end of the cue, a
 * cue that is nothing BUT a label — which happens at a turn boundary — keeps
 * "JACK:" as a spoken word, and every quote spanning that turn mismatches.
 */
const SPEAKER = /^\s*([A-Z][\w'’.-]*(?:\s+[A-Z][\w'’.-]*){0,3})\s*:(?:\s+|$)/;

/** Cue markup: voice and class tags, inline timestamps, anything angled. */
const MARKUP = /<\/?[^>]*>/g;

export function parseVtt(vtt: string): Cue[] {
  const body = vtt.replace(/\r\n?/g, "\n");
  const cues: Cue[] = [];

  for (const block of body.split(/\n{2,}/)) {
    const lines = block.split("\n").map((l) => l.trimEnd()).filter((l) => l.trim() !== "");
    if (!lines.length) continue;

    /*
     * THE THREE BLOCK KINDS THAT ARE NOT CUES, and NOTE is the one that
     * matters: it is how you comment a cue OUT, so a well-formed timing can
     * sit behind one and would otherwise parse perfectly into transcript.
     *
     * The WEBVTT header used to be tested here too and could not fire — it
     * has no timing line, so the check below skips it for a different reason.
     * STYLE and REGION are the same, and are kept only because they belong
     * beside NOTE in a reader's head rather than because they can fire.
     */
    if (/^(NOTE|STYLE|REGION)\b/.test(lines[0].trim())) continue;

    /* An optional identifier line sits before the timing. */
    const timingAt = lines.findIndex((l) => l.includes("-->"));
    if (timingAt < 0) continue;

    const [from, rest] = lines[timingAt].split("-->");
    /* Cue settings follow the end time on the same line: "align:start". */
    const to = (rest ?? "").trim().split(/\s+/)[0] ?? "";
    const startMs = stampMs(from ?? "");
    const endMs = stampMs(to);
    if (startMs === null || endMs === null || endMs < startMs) continue;

    let text = lines
      .slice(timingAt + 1)
      .join(" ")
      .replace(MARKUP, " ");
    text = decodeEntities(text).replace(/\s+/g, " ").trim();
    if (!text) continue;

    let speaker: string | undefined;
    const named = text.match(SPEAKER);
    if (named) {
      speaker = named[1];
      text = text.slice(named[0].length).trim();
      if (!text) continue;
    }

    cues.push({ startMs, endMs, text, ...(speaker ? { speaker } : {}) });
  }

  return cues;
}

/**
 * The cues as numbered words with interpolated timings.
 *
 * Interpolated BY LENGTH rather than evenly: "the" and "extraordinarily" do
 * not take the same time to say, and character count is a better proxy for
 * duration than word count by enough to matter over a seven-word cue. Still
 * an approximation, which is what the 400ms tolerance is for.
 *
 * The numbering follows `indexWords`: position in the source, counted across
 * cues in order. That is what a word id refers to, so anything that changes
 * it renumbers the source and invalidates every span pointing into it.
 */
export function vttToWords(vtt: string): IndexedWord[] {
  const out: IndexedWord[] = [];

  for (const cue of parseVtt(vtt)) {
    const words = cue.text.split(" ").filter(Boolean);
    if (!words.length) continue;

    const span = Math.max(1, cue.endMs - cue.startMs);
    const total = words.reduce((n, w) => n + w.length + 1, 0);
    let at = 0;

    for (const w of words) {
      const share = (w.length + 1) / total;
      const startMs = Math.round(cue.startMs + span * at);
      at += share;
      /* The last word ends on the cue's own end, rather than on a rounding
         error short of it: the cue boundary is the part of this that is
         actually measured. */
      const endMs = Math.round(cue.startMs + span * Math.min(1, at));
      out.push({ index: out.length, text: w, startMs, endMs: Math.max(startMs, endMs) });
    }
  }

  return out;
}

/** Where the speakers change, for a transcript that names them. */
export function speakerTurns(vtt: string): Array<{ speaker: string; startMs: number }> {
  const turns: Array<{ speaker: string; startMs: number }> = [];
  for (const cue of parseVtt(vtt)) {
    if (!cue.speaker) continue;
    if (turns[turns.length - 1]?.speaker === cue.speaker) continue;
    turns.push({ speaker: cue.speaker, startMs: cue.startMs });
  }
  return turns;
}
