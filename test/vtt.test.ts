/**
 * WEBVTT INTO WORDS.
 *
 * When a podcast feed ships a `<podcast:transcript>` it is the best find
 * Scout can make: a real transcript with real timings, published by the
 * people who made the audio, costing nothing and needing no permission. The
 * fixture is one off the wire, Descript-generated, with speaker labels — the
 * shape that actually arrives.
 *
 * What goes wrong here is quiet in the worst way: a speaker label or a
 * generator's NOTE becomes a word, and the verifier then rejects real quotes
 * that span it. Those rejections are counted as the scanning model's
 * hallucination rate, so a parser bug shows up as a model being bad.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { TOLERANCE_MS, frameAccurate, timingOf } from "../src/align.ts";
import { parseVtt, speakerTurns, vttToWords } from "../src/vtt.ts";
import { verifyQuote } from "../src/scout-verify.ts";

const VTT = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "fixtures/transcript.vtt"), "utf8");

/* ── The real file ──────────────────────────────────────────────────────── */

test("ACCEPTANCE: the real file parses into cues with sane timings", () => {
  const cues = parseVtt(VTT);
  assert.equal(cues.length, 60);

  for (const [i, c] of cues.entries()) {
    assert.ok(c.text.length > 0, `cue ${i} has no text`);
    assert.ok(c.endMs >= c.startMs, `cue ${i} ends before it starts`);
    /* Cues in a published transcript are a second or two, not a minute. */
    assert.ok(c.endMs - c.startMs < 30_000, `cue ${i} is ${c.endMs - c.startMs}ms long`);
    if (i) assert.ok(c.startMs >= cues[i - 1].startMs, `cue ${i} goes backwards`);
  }
  assert.equal(cues[0].startMs, 550);
  assert.equal(cues[0].endMs, 1540);
});

test("ACCEPTANCE: the speaker label is not a word", () => {
  /*
   * "JACK: I just came back from DEFCON" — the label is not spoken. Kept, the
   * verifier tries to match "JACK" as a word, and every quote spanning a
   * speaker change mismatches on a word nobody said. Those rejections land on
   * the scanning model's hallucination rate, so this bug reads as a bad model.
   */
  const cues = parseVtt(VTT);
  assert.equal(cues[0].speaker, "JACK");
  assert.equal(cues[0].text, "I just came back from DEFCON,");

  const words = vttToWords(VTT);
  for (const w of words) {
    assert.ok(!/^JACK:?$/i.test(w.text), `"${w.text}" at ${w.index} is a speaker label`);
  }
  /* And the label is still available where a label belongs. */
  const turns = speakerTurns(VTT);
  assert.ok(turns.length >= 1);
  assert.equal(turns[0].speaker, "JACK");
});

test("ACCEPTANCE: the generator's NOTE is not the first words of the transcript", () => {
  /*
   * Descript writes "NOTE This file was generated by Descript" at the top of
   * every file it makes. Kept, the transcript opens with an advertisement and
   * a beat about the first minute matches it.
   */
  assert.match(VTT, /^WEBVTT\s*\n\s*\nNOTE/);
  const words = vttToWords(VTT);
  const opening = words.slice(0, 12).map((w) => w.text).join(" ");
  assert.ok(!/Descript/i.test(opening), opening);
  assert.ok(!/^NOTE/.test(opening), opening);
  assert.match(opening, /^I just came back from DEFCON/);
});

test("a quote from the real file verifies, with its times off the cues", () => {
  /*
   * The whole point, end to end: a published transcript read into words, and
   * a quote found in it word for word with a timestamp nothing typed.
   */
  const words = vttToWords(VTT);
  const v = verifyQuote("I just came back from DEFCON, and it was so wonderful meeting", words);
  assert.equal(v.verify, "verified");
  assert.equal(v.exact, true);
  /* The first cue starts at 0.550s and that is where the quote starts. */
  assert.equal(v.tStartS, 0.55);
  assert.ok(v.tEndS! > v.tStartS!);
});

test("words are numbered in order across cues, with no gaps", () => {
  /* The numbering IS the word id. Anything that changes it renumbers the
     source and invalidates every span pointing into it. */
  const words = vttToWords(VTT);
  assert.ok(words.length > 200, `${words.length} words`);
  words.forEach((w, i) => assert.equal(w.index, i));
  for (let i = 1; i < words.length; i++) {
    assert.ok(words[i].startMs >= words[i - 1].startMs, `word ${i} starts before word ${i - 1}`);
    assert.ok(words[i].endMs >= words[i].startMs, `word ${i} ends before it starts`);
  }
});

test("a word's timings stay inside its own cue", () => {
  /*
   * Interpolation that overran the cue would put a word in the next speaker's
   * turn, and a scan window opened on it would start in the wrong place.
   */
  const cues = parseVtt(VTT);
  const words = vttToWords(VTT);
  let at = 0;
  for (const c of cues) {
    const n = c.text.split(" ").filter(Boolean).length;
    for (const w of words.slice(at, at + n)) {
      assert.ok(w.startMs >= c.startMs, `${w.text} starts before its cue`);
      assert.ok(w.endMs <= c.endMs, `${w.text} ends after its cue`);
    }
    at += n;
  }
  assert.equal(at, words.length);
});

test("the last word of a cue ends on the cue's own end", () => {
  /* The cue boundary is the part of this that was actually measured; a
     rounding error short of it would throw away the one real number. */
  const cues = parseVtt(VTT);
  const words = vttToWords(VTT);
  const n = cues[0].text.split(" ").filter(Boolean).length;
  assert.equal(words[n - 1].endMs, cues[0].endMs);
  assert.equal(words[0].startMs, cues[0].startMs);
});

test("a long word gets more of the cue than a short one", () => {
  /* "the" and "extraordinarily" do not take the same time to say, and
     character count is a better proxy than word count by enough to matter
     over a seven-word cue. */
  const words = vttToWords("WEBVTT\n\n00:00:00.000 --> 00:00:10.000\nthe extraordinarily\n");
  const [short, long] = words;
  assert.equal(short.text, "the");
  assert.equal(long.text, "extraordinarily");
  assert.ok(long.endMs - long.startMs > (short.endMs - short.startMs) * 2);
  assert.equal(long.endMs, 10_000);
});

/* ── What a caption timing is worth ─────────────────────────────────────── */

test("ACCEPTANCE: a caption timing says what it is worth, and refuses a frame", () => {
  /*
   * A cue is five to seven words over one to two seconds. The boundaries came
   * off an alignment and are good; the position of each word inside the cue is
   * not in the file at all, and this product interpolates it. The tolerance is
   * a stated number rather than an adjective, which is what src/align.ts is
   * for — and it is correctly not frame-accurate.
   */
  assert.equal(TOLERANCE_MS.caption, 400);
  assert.ok(TOLERANCE_MS.caption > TOLERANCE_MS.recogniser, "worse than a recogniser, and honestly so");
  assert.equal(frameAccurate(timingOf("caption")), false);
});

/* ── Markup and the other legal shapes ─────────────────────────────────── */

test("voice tags, class tags and inline timestamps are not words", () => {
  /* All three are legal inside cue text, and all three would otherwise be
     matched against a quote. */
  const vtt = [
    "WEBVTT",
    "",
    "00:00:01.000 --> 00:00:03.000",
    "<v Jack>the <c.loud>actual</c.loud> words<00:00:02.000> here</v>",
  ].join("\n");
  assert.deepEqual(vttToWords(vtt).map((w) => w.text), ["the", "actual", "words", "here"]);
});

test("ACCEPTANCE: a cue commented out with NOTE stays commented out", () => {
  /*
   * NOTE IS HOW YOU DISABLE A CUE, which is the case the header checks exist
   * for. A malformed arrow in a note falls out anyway — the timing line would
   * not parse — but a WELL-FORMED cue behind a NOTE parses perfectly, and
   * without the check it comes back as transcript.
   *
   * An earlier version of this test asserted only that the fixture's Descript
   * NOTE did not appear in the words. That passes without the check too: the
   * note has no timing line in it, so the block is skipped for a different
   * reason and the guard was never exercised.
   */
  const vtt = [
    "WEBVTT - with a comment",
    "",
    "NOTE",
    "00:00:01.000 --> 00:00:02.000",
    "this cue was taken out on purpose",
    "",
    "00:00:03.000 --> 00:00:04.000",
    "the real words",
  ].join("\n");
  assert.deepEqual(parseVtt(vtt).map((c) => c.text), ["the real words"]);

  /* And the header line is not a cue even when it carries text of its own. */
  assert.ok(!vttToWords(vtt).some((w) => /comment/.test(w.text)));
});

test("a timing with no words under it is not a cue", () => {
  /* A truncated file ends on one. Kept, it is a cue with no text that still
     counts as a cue, and anything indexing cues against words goes out of
     step from there on. */
  const vtt = "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\n\n00:00:03.000 --> 00:00:04.000\nreal\n";
  assert.deepEqual(parseVtt(vtt).map((c) => c.text), ["real"]);
});

test("short milliseconds are padded, not read as units", () => {
  /*
   * WebVTT requires three digits and plenty of files do not have them. ".5"
   * is five hundred milliseconds; read as five, every timing in the file
   * collapses towards the second mark.
   */
  assert.deepEqual(
    parseVtt("WEBVTT\n\n00:00:01.5 --> 00:00:02.25\na\n").map((c) => [c.startMs, c.endMs]),
    [[1500, 2250]],
  );
});

test("the same speaker across several cues is one turn", () => {
  /* A turn is where the speaker CHANGES. One per cue would make a
     two-speaker interview look like forty turns. */
  const vtt = [
    "WEBVTT",
    "",
    "00:00:01.000 --> 00:00:02.000",
    "JACK: first",
    "",
    "00:00:02.000 --> 00:00:03.000",
    "JACK: still me",
    "",
    "00:00:03.000 --> 00:00:04.000",
    "GUEST: now me",
    "",
    "00:00:04.000 --> 00:00:05.000",
    "JACK: back again",
  ].join("\n");
  assert.deepEqual(
    speakerTurns(vtt).map((t) => [t.speaker, t.startMs]),
    [["JACK", 1000], ["GUEST", 3000], ["JACK", 4000]],
  );
});

test("a cue identifier line before the timing is not text", () => {
  /* Numbered cues are the common export shape and the number is not spoken. */
  const vtt = "WEBVTT\n\n42\n00:00:01.000 --> 00:00:02.000\nthe words\n";
  const cues = parseVtt(vtt);
  assert.equal(cues.length, 1);
  assert.equal(cues[0].text, "the words");
});

test("cue settings after the end time are not part of the time", () => {
  /* "00:00:02.000 align:start position:10%" — a parser that took the rest of
     the line as the timestamp would reject the cue and lose the words. */
  const vtt = "WEBVTT\n\n00:00:01.000 --> 00:00:02.500 align:start position:10%\nthe words\n";
  const [c] = parseVtt(vtt);
  assert.equal(c.startMs, 1000);
  assert.equal(c.endMs, 2500);
});

test("a two-field timestamp and a comma decimal both parse", () => {
  /* MM:SS.mmm is legal WebVTT; the comma is SRT's, and SRT files get renamed
     to .vtt often enough to matter. */
  assert.deepEqual(
    parseVtt("WEBVTT\n\n01:30.500 --> 01:32.000\na\n").map((c) => [c.startMs, c.endMs]),
    [[90_500, 92_000]],
  );
  assert.deepEqual(
    parseVtt("WEBVTT\n\n00:00:01,500 --> 00:00:02,000\na\n").map((c) => [c.startMs, c.endMs]),
    [[1500, 2000]],
  );
});

test("a cue over multiple lines is one cue, joined", () => {
  const vtt = "WEBVTT\n\n00:00:01.000 --> 00:00:03.000\nthe first line\nand the second\n";
  const [c] = parseVtt(vtt);
  assert.equal(c.text, "the first line and the second");
});

test("entities in cue text decode, because the verifier compares words", () => {
  const vtt = "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\ndon&#39;t say &quot;that&quot; &amp; leave\n";
  assert.equal(parseVtt(vtt)[0].text, 'don\'t say "that" & leave');
});

test("a broken cue is skipped and the rest of the file survives", () => {
  /*
   * A truncated download, or a cue whose end precedes its start. One bad cue
   * must not cost the other nine hundred.
   */
  const vtt = [
    "WEBVTT",
    "",
    "00:00:01.000 --> 00:00:02.000",
    "first",
    "",
    "00:00:09.000 --> 00:00:04.000",
    "backwards",
    "",
    "not a timing at all",
    "",
    "00:00:05.000 --> 00:00:06.000",
    "last",
  ].join("\n");
  assert.deepEqual(parseVtt(vtt).map((c) => c.text), ["first", "last"]);
});

test("an empty file and a header-only file are no words, not one bad one", () => {
  assert.deepEqual(vttToWords(""), []);
  assert.deepEqual(vttToWords("WEBVTT\n"), []);
  assert.deepEqual(vttToWords("WEBVTT\n\nNOTE just a note\n"), []);
});

test("CRLF line endings parse, because half the files on the web have them", () => {
  /*
   * TWO CUES, NOT ONE. Blocks are split on a blank line, and in a CRLF file
   * that separator is "\r\n\r\n" — which does not match "\n\n". Without
   * normalising first, the whole file is one block: the first timing is found,
   * everything after it becomes that cue's text, and every later cue
   * disappears into it. A one-cue fixture cannot show that, because one block
   * and one cue are the same thing.
   */
  const vtt = [
    "WEBVTT",
    "",
    "00:00:01.000 --> 00:00:02.000",
    "the first words",
    "",
    "00:00:03.000 --> 00:00:04.000",
    "the second words",
  ].join("\r\n");
  assert.deepEqual(
    parseVtt(vtt).map((c) => [c.startMs, c.text]),
    [[1000, "the first words"], [3000, "the second words"]],
  );
  /* And no stray carriage return survives into a word the verifier compares. */
  for (const w of vttToWords(vtt)) assert.ok(!/[\r\n]/.test(w.text), JSON.stringify(w.text));
});

test("a colon mid-sentence is not a speaker label", () => {
  /*
   * "I told him: never again" has a colon and no speaker. Stripping to the
   * colon would delete the first half of the sentence, and the half it
   * deletes is the half with the subject in it.
   */
  const vtt = "WEBVTT\n\n00:00:01.000 --> 00:00:03.000\nI told him: never again\n";
  const [c] = parseVtt(vtt);
  assert.equal(c.speaker, undefined);
  assert.equal(c.text, "I told him: never again");
});

test("a lower-case word before a colon is not a speaker either", () => {
  const vtt = "WEBVTT\n\n00:00:01.000 --> 00:00:03.000\nnote: this is said aloud\n";
  assert.equal(parseVtt(vtt)[0].speaker, undefined);
});

test("a cue that is nothing but a speaker label is not a cue", () => {
  /* It would be an empty turn with a timestamp, and a word count of zero
     between two real cues shifts nothing — but a cue with no words in it
     would otherwise make it into the cue list and be counted. */
  const vtt = "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nJACK:\n";
  assert.deepEqual(parseVtt(vtt), []);
});
