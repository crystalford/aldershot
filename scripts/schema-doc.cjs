#!/usr/bin/env node
/*
 * WRITES THE SCHEMA DOCUMENT FROM THE SCHEMA THAT RUNS.
 *
 * This repo has no migration runner. src/schema.ts says so in its own header
 * and deploy.yml skips one: every table is created lazily on first request,
 * and the numbered files in migrations/ were never executed by anything. They
 * are documentation that was written by hand, and by the time this script was
 * written 0006_v2_core.sql disagreed with the running schema about twelve
 * tables and had never heard of nine more.
 *
 * So the schema document is generated, not written. migrations/schema.sql is
 * the current shape of the database, and `npm run check` fails if it has
 * fallen behind. The numbered files stay where they are as history — nothing
 * in this product is deleted — and nothing reads them.
 *
 * Run: npm run schema
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'migrations/schema.sql');

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name.endsWith('.ts')) out.push(p);
  }
  return out;
}

const HEADER = `-- THE SCHEMA, AS IT ACTUALLY IS.
--
-- Generated by scripts/schema-doc.cjs from the CREATE statements in src/.
-- Do not edit: run \`npm run schema\`. \`npm run check\` fails if this file has
-- fallen behind the code, which is the only way a schema document stays true.
--
-- There is no migration runner in this project. Every statement here is
-- IF NOT EXISTS and runs lazily on first request (ensureV2Schema and the
-- other ensure*Schema functions). The numbered files beside this one are
-- history: hand-written, never executed, and out of date from 0006 onward.
--
-- Columns added to a table after the fact live in ADDED_COLUMNS in
-- src/schema.ts and are listed at the end of this file.

`;

const statements = [];
const seen = new Set();
for (const f of walk(path.join(ROOT, 'src'))) {
  const src = fs.readFileSync(f, 'utf8');
  /* UNIQUE is optional and was not, which is how the first unique index in
     src/ never reached this file. A generator that quietly ignores a form of
     the statement it exists to collect is worse than no generator: the
     document it writes looks complete. */
  for (const m of src.matchAll(/`(CREATE (?:TABLE|(?:UNIQUE )?INDEX) IF NOT EXISTS [\s\S]*?)`/g)) {
    const stmt = m[1];
    const name = (stmt.match(/create (?:table|(?:unique )?index) if not exists (\w+)/i) || [])[1];
    if (!name || seen.has(name)) continue;
    /*
     * A TRUNCATED STATEMENT IS NEVER WRITTEN OUT.
     *
     * The capture above is delimited by backticks, so a single backtick
     * anywhere inside the statement -- including inside a SQL comment --
     * ends it early. That is the same trap src/ui/client.ts carries a
     * warning about, one level up: there the template literal breaks and
     * tsc says so, here the generator just captures less and reports the
     * same statement count as before. Measured: a comment containing a
     * backticked filename cut the rules table off after three columns and
     * wrote "*;" where the rest of it should have been, and the only
     * symptom was a schema document missing five columns, two uniques and
     * a primary key.
     *
     * Parentheses have to balance and the statement has to close on one,
     * or this stops rather than writing a document that looks complete.
     */
    let depth = 0;
    for (const ch of stmt) {
      if (ch === '(') depth += 1;
      else if (ch === ')') depth -= 1;
    }
    if (depth !== 0 || !/\)\s*$/.test(stmt)) {
      console.error(
        `\nschema-doc: ${name} in ${path.relative(ROOT, f)} did not close.\n` +
          `A backtick inside the statement ends the capture early -- check its comments.\n`,
      );
      process.exit(1);
    }
    seen.add(name);
    statements.push({ file: path.relative(ROOT, f), sql: stmt.replace(/\n   /g, '\n  ').trim() });
  }
}

const added = [];
for (const f of walk(path.join(ROOT, 'src'))) {
  for (const m of fs.readFileSync(f, 'utf8').matchAll(/ddl:\s*"(ALTER TABLE [^"]+)"/g)) {
    added.push(m[1]);
  }
}

let body = '';
let from = '';
for (const s of statements) {
  if (s.file !== from) {
    body += `-- from ${s.file}\n`;
    from = s.file;
  }
  body += s.sql + ';\n\n';
}
if (added.length) {
  body += '-- Added after the fact (ADDED_COLUMNS; applied only where missing).\n';
  body += added.map((a) => a + ';').join('\n') + '\n';
}

fs.writeFileSync(OUT, HEADER + body);
console.log(`migrations/schema.sql — ${statements.length} statements, ${added.length} added columns`);
