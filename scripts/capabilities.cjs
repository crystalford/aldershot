/**
 * WHAT HAS TO BE CONFIGURED, WHAT EACH ONE NEEDS, AND WHAT ITS ABSENCE COSTS.
 *
 * One list, read by two things that used to each carry their own idea of it:
 *
 *   scripts/preflight.cjs      asks a RUNNING deployment, via /api/preflight
 *   scripts/deploy-readout.mjs says what the DEPLOY just configured
 *
 * They were going to drift. A readiness report that disagrees with the deploy
 * about what is switched on is worse than having neither, because one of them
 * is lying and nothing says which.
 *
 * WHY THE DEPLOY NEEDS ITS OWN READER AT ALL. /api/preflight is owner-only
 * (src/index.ts), so reading it needs a session, and getting a session needs
 * the sign-in that it reports on. That catch-22 is not academic: MAIL_FROM was
 * empty for a month, nobody could sign in to aldershot.io, and the only way to
 * find out was reading the tail of a failed deploy's log.
 *
 * `env` is the variable names to test. `prose` fields are for people.
 * `setByDeploy` marks the one the deploy generates itself, which the readout
 * must not report as missing just because it is not in the job's environment.
 *
 * Ordered by what it stops. Sign-in first, because an account nobody can
 * create is the one failure that makes every other one moot.
 */
